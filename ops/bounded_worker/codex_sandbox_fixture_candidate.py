GATE_ARG = 'exec(bytes.fromhex("' + GATE.encode('ascii').hex() + '"))'


def command(executable, work, home, mode):
    """Build fixed CLI arguments with adapter-derived pilot restrictions."""
    if mode not in ('normal', 'interrupted'):
        raise ValueError('invalid_probe_mode')
    paths = (executable, work, home)
    if any(not isinstance(p, str) or not p.startswith('/') or str(Path(p)) != p
           or '..' in Path(p).parts for p in paths):
        raise ValueError('invalid_probe_path')
    workspace = Path(work)
    for denied in (home + '/.codex', *DENIED, executable):
        denied_path = Path(denied)
        if workspace == denied_path or workspace in denied_path.parents or denied_path in workspace.parents:
            raise ValueError('overlapping_probe_paths')
    fs = {':minimal': 'read', work: 'write', **dict.fromkeys((home + '/.codex', *DENIED), 'deny'),
          executable: 'read'}
    if len(fs) != 3 + len(DENIED) + 1:
        raise ValueError('overlapping_probe_paths')
    entries = ', '.join(f'{json.dumps(k)} = {json.dumps(v)}' for k, v in fs.items())
    args = [executable, '-c', 'default_permissions="pilot"',
            '-c', f'permissions.pilot.filesystem = {{ {entries} }}',
            '-c', 'permissions.pilot.network.enabled=false', '-c', 'web_search="disabled"',
            '-c', 'shell_environment_policy.inherit="none"',
            '-c', 'shell_environment_policy.set = { PATH = "/usr/bin:/bin" }',
            '-c', 'model_reasoning_effort="medium"']
    for feature in DISABLED:
        args += ['--disable', feature]
    # Managed configuration is intentionally omitted pending a reviewed,
    # credential-free network boundary for CLI configuration bootstrap.
    return args + ['--enable', 'code_mode_host', 'sandbox', '--permission-profile', 'pilot',
                   '-C', work, '--', '/usr/bin/python3', '-I', '-S', '-B', '-c', PROBE_ARG, mode]


class CandidateWorker:
    """Worker adapter only; a separately reviewed supervisor must verify cleanup."""
    def __init__(self, pinned_binary, account, mode, supervisor, credential_paths, revalidate_scope):
        if not callable(getattr(supervisor, 'observe', None)):
            raise ValueError('live_probe_observer_required')
        if (type(credential_paths) is not tuple or not credential_paths or not callable(revalidate_scope)):
            raise ValueError('credential_scope_required')
        self.pinned_binary, self.account, self.mode = pinned_binary, account, mode
        self.supervisor = supervisor
        self.credential_paths, self.revalidate_scope = credential_paths, revalidate_scope
        self.child = None
        self.identity = None

    def run(self, task, work, containment):
        del task
        if (getattr(getattr(containment, 'backend', None), 'unit', None) != self.supervisor.unit
                or self.supervisor.uid != self.account.pw_uid or self.supervisor.mode != self.mode):
            raise ValueError('probe_supervisor_binding_mismatch')
        pinned = self.pinned_binary._binary()
        executable = str(self.pinned_binary.executable)
        home = self.account.pw_dir
        args = command(executable, str(work), home, self.mode)
        gated_args = ['/usr/bin/python3', '-I', '-S', '-B', '-c', GATE_ARG,
                      json.dumps({'argv': args, 'uid': self.account.pw_uid, 'gid': self.account.pw_gid,
                                  'stores': self.credential_paths, 'control': str(work)},
                                 separators=(',', ':'), ensure_ascii=True)]
        if pinned != self.pinned_binary._binary():
            raise ValueError('probe_binary_changed')
        env = {'HOME': home, 'CODEX_HOME': home + '/.codex',
               'PATH': home + '/.local/bin:/usr/bin:/bin', 'LANG': 'C.UTF-8',
               'GIT_TERMINAL_PROMPT': '0', 'GIT_CONFIG_NOSYSTEM': '1'}
        self.child = containment.launch(gated_args, cwd=work, env=env, user=self.account.pw_uid,
                                        group=self.account.pw_gid, extra_groups=[],
                                        stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                        stderr=subprocess.PIPE, start_new_session=True, bufsize=0)
        if pinned != self.pinned_binary._binary():
            raise ValueError('probe_binary_changed')
        gate = read_line(self.child.stdout, seconds=50)
        if gate != {'gate': 'waiting', 'credentials': 'denied'} or self.child.poll() is not None:
            raise ValueError('pre_exec_gate_unverified')
        if containment.backend.verify_gate(gated_args) is not True:
            raise ValueError('pre_exec_gate_unverified')
        if self.revalidate_scope() != self.credential_paths:
            raise ValueError('credential_scope_changed')
        # The separately required socket preflight remains external.
        if self.child.stdin.write(b'g') != 1:
            raise ValueError('pre_exec_gate_release_failed')
        self.child.stdin.flush()
        report = read_line(self.child.stdout)
        if (type(report) is not dict or set(report) != {'checks', 'local_pid'}
                or report['checks'] != 'writable_workspace_and_readonly_metadata'
                or type(report['local_pid']) is not int or report['local_pid'] <= 0):
            raise ValueError('invalid_probe_report')
        self.identity = self.supervisor.observe(report['local_pid'])
        if (type(self.identity) is not tuple or len(self.identity) != 4
                or any(type(value) is not int or value <= 0 for value in self.identity)):
            raise ValueError('probe_identity_unverified')
        if self.mode == 'normal':
            self.child.stdin.write(b'x')
            self.child.stdin.flush()
            if self.child.wait(timeout=10) != 0:
                raise ValueError('probe_exit_failed')
            if pinned != self.pinned_binary._binary():
                raise ValueError('probe_binary_changed')
            return {'status': 'completed', 'errors': [], 'usage': None}
        if self.child.poll() is not None:
            raise ValueError('probe_not_running')
        if self.supervisor.observe(report['local_pid']) != self.identity:
            raise ValueError('probe_identity_changed')
        if pinned != self.pinned_binary._binary():
            raise ValueError('probe_binary_changed')
        return {'status': 'timeout', 'errors': [], 'usage': None}
